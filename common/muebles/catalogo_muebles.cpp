const std::vector<DatosDeMueble>& CatalogoDeMuebles::todos() {
    static const std::vector<DatosDeMueble> muebles = [] {
        std::vector<DatosDeMueble> armados;
        uint16_t indice = 0;
        for (const FilaDeMueble& fila : FILAS) {
            DatosDeMueble mueble;
            mueble.item = static_cast<TipoItem>(PRIMER_ITEM_DE_MUEBLE + indice);
            mueble.objeto = static_cast<TipoObjeto>(PRIMER_OBJETO_DE_MUEBLE + indice);
            mueble.nombre = fila.nombre;
            mueble.columna = fila.columna;
            mueble.fila = fila.fila;
            mueble.ancho = fila.ancho;
            mueble.alto = fila.alto;
            mueble.alto_del_pie = fila.alto_del_pie;
            mueble.tipo = fila.tipo;
            mueble.columna_del_frente = fila.columna_del_frente;
            mueble.fila_del_frente = fila.fila_del_frente;
            armados.push_back(mueble);
            ++indice;
        }
        return armados;
    }();
    return muebles;
}

const DatosDeMueble* CatalogoDeMuebles::buscar(TipoItem item) {
    const int indice = static_cast<int>(item) - PRIMER_ITEM_DE_MUEBLE;
    if (indice < 0 || indice >= static_cast<int>(todos().size())) {
        return nullptr;
    }
    return &todos()[indice];
}

const DatosDeMueble* CatalogoDeMuebles::buscar(TipoObjeto objeto) {
    const int indice = static_cast<int>(objeto) - PRIMER_OBJETO_DE_MUEBLE;
    if (indice < 0 || indice >= static_cast<int>(todos().size())) {
        return nullptr;
    }
    return &todos()[indice];
}
