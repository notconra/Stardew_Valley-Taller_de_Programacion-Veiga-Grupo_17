const std::vector<DatosDeMueble>& CatalogoDeMuebles::vistas() {
    static const std::vector<DatosDeMueble> armadas = [] {
        std::vector<DatosDeMueble> resultado;
        int indice = 0;
        for (const FilaDeVista& fila : VISTAS) {
            DatosDeMueble vista;
            vista.item = static_cast<TipoItem>(PRIMER_ITEM_DE_MUEBLE + fila.mueble);
            vista.objeto = static_cast<TipoObjeto>(PRIMER_OBJETO_DE_MUEBLE + indice);
            vista.nombre = NOMBRES[fila.mueble];
            vista.columna = fila.columna;
            vista.fila = fila.fila;
            vista.ancho = fila.ancho;
            vista.alto = fila.alto;
            vista.alto_del_pie = fila.alto_del_pie;
            vista.tipo = fila.tipo;
            vista.espejado = fila.espejado;
            vista.siguiente =
                static_cast<TipoObjeto>(PRIMER_OBJETO_DE_MUEBLE + indice + fila.hasta_la_siguiente);
            vista.columna_del_frente = fila.columna_del_frente;
            vista.fila_del_frente = fila.fila_del_frente;
            resultado.push_back(vista);
            ++indice;
        }
        return resultado;
    }();
    return armadas;
}

const std::vector<const DatosDeMueble*>& CatalogoDeMuebles::muebles() {
    static const std::vector<const DatosDeMueble*> primeras = [] {
        std::vector<const DatosDeMueble*> resultado;
        for (const DatosDeMueble& vista : vistas()) {
            if (resultado.empty() || resultado.back()->item != vista.item) {
                resultado.push_back(&vista);
            }
        }
        return resultado;
    }();
    return primeras;
}

const DatosDeMueble* CatalogoDeMuebles::buscar(TipoItem item) {
    const int indice = static_cast<int>(item) - PRIMER_ITEM_DE_MUEBLE;
    if (indice < 0 || indice >= static_cast<int>(muebles().size())) {
        return nullptr;
    }
    return muebles()[indice];
}

const DatosDeMueble* CatalogoDeMuebles::buscar(TipoObjeto objeto) {
    const int indice = static_cast<int>(objeto) - PRIMER_OBJETO_DE_MUEBLE;
    if (indice < 0 || indice >= static_cast<int>(vistas().size())) {
        return nullptr;
    }
    return &vistas()[indice];
}
